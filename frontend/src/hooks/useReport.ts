/* ============================================================
   useReport — Report export hook
   Real mode: downloads the report generated by the backend
   (/api/v1/report/{id}/export). If the server is unreachable or
   the scan is unknown to it, falls back to client-side generation.
   Mock mode: always client-side.
   ============================================================ */

import { useState, useCallback } from 'react'
import { exportAsJson, exportAsHtml, downloadBlob } from '../utils/exportReport'
import { reportApi, toApiError } from '../services'
import type { ReportFormat } from '../services'
import { USE_MOCK } from '../config'
import type { ScanResult } from '../types'

export type { ReportFormat }

export interface UseReportOptions {
  /** Force client-side generation. @default USE_MOCK */
  clientOnly?: boolean
}

export interface UseReportReturn {
  /** Format currently being exported (null when idle) */
  exporting: ReportFormat | null
  /** Last export error message, if any */
  error: string | null
  /** Export the given result in the chosen format. Resolves true on success. */
  exportReport: (result: ScanResult, format: ReportFormat) => Promise<boolean>
  /** Clear the last error */
  clearError: () => void
}

function exportClientSide(result: ScanResult, format: ReportFormat): void {
  if (format === 'json') exportAsJson(result)
  else exportAsHtml(result)
}

export function useReport(options: UseReportOptions = {}): UseReportReturn {
  const { clientOnly = USE_MOCK } = options
  const [exporting, setExporting] = useState<ReportFormat | null>(null)
  const [error, setError] = useState<string | null>(null)

  const exportReport = useCallback(
    async (result: ScanResult, format: ReportFormat): Promise<boolean> => {
      setError(null)
      setExporting(format)
      try {
        if (!clientOnly) {
          try {
            const blob = await reportApi.exportReport(result.scan_id, format)
            downloadBlob(blob, reportApi.filename(result.scan_id, format))
            return true
          } catch (err) {
            // Server export failed — the result is already in memory, so fall back
            console.warn('[useReport] Server export failed, using client-side:', toApiError(err).message)
          }
        }
        exportClientSide(result, format)
        return true
      } catch (err) {
        setError(err instanceof Error ? err.message : 'Failed to export report')
        return false
      } finally {
        setExporting(null)
      }
    },
    [clientOnly],
  )

  const clearError = useCallback(() => setError(null), [])

  return { exporting, error, exportReport, clearError }
}
